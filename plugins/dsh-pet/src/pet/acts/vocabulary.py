"""动作语义表：素材名 → 给模型看的短名、分类、触发词。

为什么要有这张表
----------------
素材名是**做动画的人**起的名（「小幅度原地360度旋转展示」「工作状态-忙碌点按」）。
直接塞给模型有三重问题：太长（占 token）、带素材工艺词（"原地""工作状态"是说给
美术听的）、跨角色包不稳定（别的包没有这段素材，名字也不同，
``work_choreo.ACTION_HINTS`` 已经因为这一点立过"意图 → 关键词 → 可播集合"的规矩）。

这张表只负责**语义**：一个模型能念出来的短名、一个分类（提示词按类分行列，省
token 又方便它按场景挑）、一组触发词（``ActRepertoire.resolve`` 用它把近义说法
收敛到同一条素材上）。表里没有的素材名不会失效，走 ``repertoire`` 的合成规则
（短名 = 素材名本身，关键词 = 屏幕上的字），保证换角色包也能用。

两种分类口径
------------
**引擎口径**（``catalog.build_categories``）按目录分：``idle/ turn/ move/ click/
drag/ random/``——它回答"这段素材怎么进调度器"。
**本表口径**按**这个动作用在什么场合**分——它回答"模型什么时候该想起它"。
两者不是一一对应：``random/`` 里的 89 段素材，语义上分属情绪、工作、吃喝、节庆、
日常、玩、演出七类，混在一起列给模型等于没分类。

素材名以 ``assets/characters/<id>/videos/`` 下的**文件名**为准
（``tests/test_act_repertoire.py`` 里有一条拿真实目录对账的用例）。
"""
